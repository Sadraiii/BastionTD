            var pixels: [(Int, Int)] = []
            var maxX = 0
            for (y, row) in rows.enumerated() {
                for (x, c) in row.enumerated() where c == "#" {
                    pixels.append((x, y))
                    maxX = max(maxX, x)
                }
            }
            result[char] = Glyph(width: maxX + 1, pixels: pixels)
        }
        return result
    }()

