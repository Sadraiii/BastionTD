import Foundation

/// A 5x7 bitmap font used for titles, numbers and in-world labels.
/// Glyphs are proportional: empty columns are trimmed and one pixel of spacing is added.
enum PixelFont {
    static let glyphHeight = 7
    static let spaceWidth = 3
    static let letterSpacing = 1

    struct Glyph {
        let width: Int
        /// Lit pixel coordinates (x, y) with y = 0 at the top.
        let pixels: [(Int, Int)]
    }

    static func glyph(for character: Character) -> Glyph? {
        let key = Character(character.uppercased())
        return glyphs[key]
    }

    /// Width in font pixels of `text` (without any outline).
    static func width(of text: String) -> Int {
        var total = 0
        for (i, char) in text.enumerated() {
            if i > 0 { total += letterSpacing }
            total += glyph(for: char)?.width ?? spaceWidth
        }
        return total
    }

    /// Calls `plot` for every lit pixel of `text`, laid out from x = 0.
    static func layout(_ text: String, plot: (Int, Int) -> Void) {
        var cursor = 0
        for (i, char) in text.enumerated() {
            if i > 0 { cursor += letterSpacing }
            guard let glyph = glyph(for: char) else {
                cursor += spaceWidth
                continue
            }
            for (x, y) in glyph.pixels { plot(cursor + x, y) }
            cursor += glyph.width
        }
    }

    /// Renders text into a canvas with an optional 1px outline.
    static func render(_ text: String, color: PixelColor, outline: PixelColor? = Pal.ink) -> PixelCanvas {
        let pad = outline == nil ? 0 : 1
        var canvas = PixelCanvas(width: width(of: text) + pad * 2, height: glyphHeight + pad * 2)
        layout(text) { x, y in canvas.set(x + pad, y + pad, color) }
        if let outline { canvas.outline(outline, diagonals: true) }
        return canvas
    }

    private static let glyphs: [Character: Glyph] = {
        var result: [Character: Glyph] = [:]
